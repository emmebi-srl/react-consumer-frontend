import { FormControlLabel, FormHelperText, Stack, Switch, TextField } from '@mui/material';
import { Control, Controller, Path, useWatch } from 'react-hook-form';
import z from 'zod';

/** Characters Windows refuses in a file name (the placeholders' braces are fine). */
export const whatsappMailBodyPdfFileNameSchema = z
  .string()
  .trim()
  .max(150, { message: 'Massimo 150 caratteri' })
  .regex(/^[^\\/:*?"<>|]*$/, { message: 'Il nome non può contenere \\ / : * ? " < > |' });

interface WhatsappMailBodyPdfValues {
  whatsappMailBodyPdf: boolean;
  whatsappMailBodyPdfFileName: string;
}

/**
 * WhatsApp can't show the email: when the dispatch has no attachment (an attachment always wins), the document
 * header of the WhatsApp template gets the email body (template with the placeholders of each recipient) as PDF,
 * generated by the server when sending. Not attached to the email.
 */
const WhatsappMailBodyPdfFields = <T extends WhatsappMailBodyPdfValues>({ control }: { control: Control<T> }) => {
  const enabledName = 'whatsappMailBodyPdf' as Path<T>;
  const fileNameName = 'whatsappMailBodyPdfFileName' as Path<T>;
  const isEnabled = useWatch({ control, name: enabledName }) as boolean;

  return (
    <Stack direction="column" sx={{ gap: 1 }}>
      <Controller
        control={control}
        name={enabledName}
        render={({ field }) => (
          <FormControlLabel
            control={<Switch checked={!!field.value} onChange={(event) => field.onChange(event.target.checked)} />}
            label="Su WhatsApp invia l'email in PDF"
          />
        )}
      />
      <FormHelperText sx={{ mt: -1 }}>
        Per i template WhatsApp con intestazione documento, quando l'invio non ha già un allegato (es. l'estratto conto,
        che ha la precedenza). Non viene allegato all'email.
      </FormHelperText>
      {isEnabled && (
        <Controller
          control={control}
          name={fileNameName}
          render={({ field, fieldState }) => (
            <TextField
              {...field}
              label="Nome del PDF"
              fullWidth
              error={!!fieldState.error}
              helperText={
                fieldState.error?.message ??
                "Facoltativo, senza .pdf. Accetta i segnaposto, es. Estratto conto {{customer_name}}. Se vuoto, usa l'oggetto dell'email."
              }
            />
          )}
        />
      )}
    </Stack>
  );
};

export default WhatsappMailBodyPdfFields;
